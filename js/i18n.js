class AruzI18n {
  constructor() {
    this.supportedLangs = ['es', 'en', 'fr'];
    this.defaultLang = 'es';
    this.currentLang = this.detectLanguage();
    this.init();
  }

  detectLanguage() {
    // 1. URL search param ?lang=xx
    const urlParams = new URLSearchParams(window.location.search);
    const urlLang = urlParams.get('lang')?.toLowerCase();
    if (urlLang && this.supportedLangs.includes(urlLang)) {
      localStorage.setItem('aruz_lang', urlLang);
      return urlLang;
    }

    // 2. localStorage saved preference
    const savedLang = localStorage.getItem('aruz_lang')?.toLowerCase();
    if (savedLang && this.supportedLangs.includes(savedLang)) {
      return savedLang;
    }

    // 3. Browser locale auto-detection
    const browserLangs = navigator.languages || [navigator.language || 'es'];
    for (const bLang of browserLangs) {
      const short = bLang.substring(0, 2).toLowerCase();
      if (short === 'fr') return 'fr';
      if (short === 'en') return 'en';
      if (short === 'es') return 'es';
    }

    return this.defaultLang;
  }

  init() {
    this.applyLanguage(this.currentLang, false);
    this.renderLanguageSwitchers();
  }

  setLanguage(lang) {
    if (!this.supportedLangs.includes(lang)) return;
    this.currentLang = lang;
    localStorage.setItem('aruz_lang', lang);
    this.applyLanguage(lang, true);
    this.updateSwitcherUI();
  }

  applyLanguage(lang, userTriggered = false) {
    document.documentElement.setAttribute('lang', lang);
    const dict = aruzTranslations[lang] || aruzTranslations[this.defaultLang];

    // Translate all [data-i18n]
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Translate all [data-i18n-html]
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    // Translate all [data-i18n-placeholder]
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Translate all [data-i18n-title]
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) {
        el.setAttribute('title', dict[key]);
      }
    });

    // Translate all [data-i18n-aria]
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      if (dict[key]) {
        el.setAttribute('aria-label', dict[key]);
      }
    });

    // Update document title if present
    const pageTitleKey = document.querySelector('meta[name="i18n-title-key"]')?.getAttribute('content');
    if (pageTitleKey && dict[pageTitleKey]) {
      document.title = dict[pageTitleKey];
    }

    // Trigger custom event
    window.dispatchEvent(new CustomEvent('aruzLanguageChanged', { detail: { lang } }));
  }

  renderLanguageSwitchers() {
    const switcherHTML = `
      <div class="aruz-lang-switcher inline-flex items-center bg-black/40 border border-dorado-aruz/30 rounded-full px-2 py-1 text-[11px] font-sans font-bold tracking-wider backdrop-blur-md">
        <button type="button" onclick="window.AruzI18nInstance.setLanguage('es')" class="lang-btn px-2 py-0.5 rounded-full transition-all ${this.currentLang === 'es' ? 'bg-dorado-aruz text-carbon-aruz font-extrabold shadow-sm' : 'text-white/70 hover:text-dorado-aruz'}" data-lang="es">ES</button>
        <span class="text-white/20 mx-0.5">·</span>
        <button type="button" onclick="window.AruzI18nInstance.setLanguage('en')" class="lang-btn px-2 py-0.5 rounded-full transition-all ${this.currentLang === 'en' ? 'bg-dorado-aruz text-carbon-aruz font-extrabold shadow-sm' : 'text-white/70 hover:text-dorado-aruz'}" data-lang="en">EN</button>
        <span class="text-white/20 mx-0.5">·</span>
        <button type="button" onclick="window.AruzI18nInstance.setLanguage('fr')" class="lang-btn px-2 py-0.5 rounded-full transition-all ${this.currentLang === 'fr' ? 'bg-dorado-aruz text-carbon-aruz font-extrabold shadow-sm' : 'text-white/70 hover:text-dorado-aruz'}" data-lang="fr">FR</button>
      </div>
    `;

    // Inject into headers with class .header-lang-slot or create next to nav
    document.querySelectorAll('.header-lang-slot').forEach(slot => {
      slot.innerHTML = switcherHTML;
    });
  }

  updateSwitcherUI() {
    document.querySelectorAll('.aruz-lang-switcher').forEach(switcher => {
      switcher.querySelectorAll('.lang-btn').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        if (btnLang === this.currentLang) {
          btn.className = 'lang-btn px-2 py-0.5 rounded-full transition-all bg-dorado-aruz text-carbon-aruz font-extrabold shadow-sm';
        } else {
          btn.className = 'lang-btn px-2 py-0.5 rounded-full transition-all text-white/70 hover:text-dorado-aruz';
        }
      });
    });
  }
}

